/**
 * LOT-FM-001 / BASIC — supplier quote CSV intake (SERVER ONLY).
 * Row format = RFQ return line: line, supplier, unit USD, MOQ, lead days, valid days, quote date.
 * Pure: parses and validates, never writes. Rejects the whole sheet on any bad row.
 */
import { RATION_MANIFEST } from '#shared/basics/manifest'
import type { Quote } from '#server/basics/quotes'

export type QuoteSheet = { quotes: Record<string, Quote>; errors: string[] }

const LINES = new Set(RATION_MANIFEST.map((i) => i.line))

export const parseQuotesCsv = (csv: string): QuoteSheet => {
  const quotes: Record<string, Quote> = {}
  const errors: string[] = []
  csv.split(/\r?\n/).forEach((raw, n) => {
    const row = raw.trim()
    if (!row || row.startsWith('#') || /^line\b/i.test(row)) return
    const at = `ROW ${n + 1}`
    const [line, supplier, usd, moq, lead, valid, on] = row.split(',').map((c) => c.trim())
    const cents = Math.round(Number(usd) * 100)
    if (!LINES.has(line)) return void errors.push(`${at}: UNKNOWN LINE "${line}"`)
    if (quotes[line]) return void errors.push(`${at}: DUPLICATE LINE ${line}`)
    if (!supplier) return void errors.push(`${at}: LINE ${line} NO SUPPLIER`)
    if (!(cents > 0)) return void errors.push(`${at}: LINE ${line} BAD UNIT USD "${usd}"`)
    if (!(Number(moq) > 0) || !Number.isInteger(Number(moq))) return void errors.push(`${at}: LINE ${line} BAD MOQ "${moq}"`)
    if (!(Number(lead) >= 0)) return void errors.push(`${at}: LINE ${line} BAD LEAD DAYS "${lead}"`)
    if (!(Number(valid) > 0)) return void errors.push(`${at}: LINE ${line} BAD VALID DAYS "${valid}"`)
    if (!/^\d{4}-\d{2}-\d{2}$/.test(on) || Number.isNaN(Date.parse(on)))
      return void errors.push(`${at}: LINE ${line} BAD DATE "${on}" (YYYY-MM-DD)`)
    quotes[line] = { supplier, unitCents: cents, moq: Number(moq), quotedOn: on, validDays: Number(valid) }
  })
  return { quotes, errors }
}

/** Source text for quotes.data.ts. */
export const renderQuoteData = (quotes: Record<string, Quote>): string =>
  [
    "import type { Quote } from '#server/basics/quotes'",
    '',
    '/** Generated by `npm run basics:quotes -- <sheet.csv> --write`. Supplier-confidential. */',
    `export const QUOTE_DATA: Record<string, Quote> = ${JSON.stringify(quotes, null, 2)}`,
    '',
  ].join('\n')
