#!/usr/bin/env bash
# Writes firmware/include/root_ca.h with the ISRG Root X1 certificate (Let's Encrypt),
# which anchors lot-systems.com. Run once before building EVT/PVT firmware.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
out="$here/../firmware/include/root_ca.h"
pem="$(curl -fsSL https://letsencrypt.org/certs/isrgrootx1.pem)"
{
  echo '// Generated by tools/fetch_root_ca.sh — ISRG Root X1'
  echo '#pragma once'
  echo 'static const char LOT_ROOT_CA_PEM[] = R"PEM('
  echo "$pem"
  echo ')PEM";'
} > "$out"
echo "wrote $out"
